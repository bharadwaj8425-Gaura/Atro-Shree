-- Astro-Shree tables. Written only by the website backend (service role). RLS on, no public policies.
create table if not exists public.astro_events (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  event text not null,
  visitor_id text,
  consent boolean not null default false,
  lang text,
  name text, phone text, email text, city text,
  birth jsonb,
  meta jsonb,
  ip_hash text, country text, user_agent text
);
create index if not exists astro_events_created_idx on public.astro_events (created_at desc);
create index if not exists astro_events_event_idx on public.astro_events (event);
create index if not exists astro_events_visitor_idx on public.astro_events (visitor_id);
alter table public.astro_events enable row level security;
comment on table public.astro_events is 'Astro-Shree website usage (kundli, milan, tarot, games...) and consented leads. Written only by the website backend (service role). No public access.';

create table if not exists public.astro_payments (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  paid_at timestamptz,
  order_id text unique,
  payment_id text unique,
  status text not null default 'pending',
  service text not null,
  amount_paise integer not null,
  name text, phone text, email text, visitor_id text,
  details jsonb,
  screenshot text,
  verdict jsonb,
  meta jsonb,
  fulfilled boolean not null default false
);
create index if not exists astro_payments_created_idx on public.astro_payments (created_at desc);
alter table public.astro_payments enable row level security;
comment on table public.astro_payments is 'Astro-Shree bookings paid by UPI (UTR + screenshot, AI-checked). Written only by the website backend. No public access.';

create table if not exists public.astro_reviews (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null, city text, rating smallint not null default 5, text text not null,
  service text, phone text, visitor_id text, ip_hash text,
  status text not null default 'pending'
);
alter table public.astro_reviews enable row level security;
comment on table public.astro_reviews is 'Astro-Shree customer reviews; shown on site only after admin approval.';
